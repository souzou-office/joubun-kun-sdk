'use strict';

const { buildLexicon, extractCitations } = require('./03_parse.cjs');

const lex = buildLexicon();
let fails = 0;
const read = (text) => {
  const r = extractCitations(text, lex);
  return {
    refs: [...r.refs.values()].map((x) => `${x.law}${x.art}`).sort(),
    other: [...r.unresolved.values()].map((x) => `${x.name}${x.art}`).sort(),
  };
};
const check = (text, refs, other) => {
  const r = read(text);
  const ok = JSON.stringify(r.refs) === JSON.stringify([...refs].sort()) &&
    (!other || JSON.stringify(r.other) === JSON.stringify([...other].sort()));
  console.log(`${ok ? 'PASS' : 'FAIL'}  ${text.replace(/\n/g, '⏎')}${ok ? '' : `  → ${JSON.stringify(r)}`}`);
  if (!ok) fails++;
};

