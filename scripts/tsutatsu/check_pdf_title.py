# 05_extract_pdf_text.py の PDF の題名の取り方（guess_title）の確かめ。¥0・PDF も pdfplumber も要らない（抜き出した行を渡す）
#
#   python -I -X utf8 scripts/tsutatsu/check_pdf_title.py
#
# 行は国税庁の PDF を pdfplumber で読んだ 1 ページ目の先頭（2026-10-22 に取り込みで題名が文の切れ端になったもの）

import os, sys, importlib.util

spec = importlib.util.spec_from_file_location('extract05', os.path.join(os.path.dirname(os.path.abspath(__file__)), '05_extract_pdf_text.py'))
m = importlib.util.module_from_spec(spec)
spec.loader.exec_module(m)

fails = 0
def check(name, got, want):
    global fails
    ok = got == want
    print(('PASS' if ok else 'FAIL') + '  ' + name + ('' if ok else '  → %r（期待 %r）' % (got, want)))
    if not ok: fails += 1

# hotei/000601/pdf/kisai07.pdf（法定調書合計表の記載要領）
check('記載要領: 【】の見出しと「記載要領」を題名にする（本文の折り返しを拾わない）', m.guess_title([
    '【給与所得の源泉徴収票等の法定調書合計表】',
    '記載要領',
    '１ 給与所得の源泉徴収票合計表',
    '(1) 「Ａ○俸給、給与、賞与等の総額」欄は、給与所得の源泉徴収票の提出省略限度額以下のため給与所',
    '得の源泉徴収票の提出を省略するものを含めたすべての給与等について記載する。',
]), '給与所得の源泉徴収票等の法定調書合計表 記載要領')

# hotei/000601/pdf/kisai02.pdf
check('記載要領: 「…について、その合計を記載する。」を拾わない', m.guess_title([
    '【国外公社債等の利子等の支払調書合計表】',
    '記載要領',
    '１ 「支払件数（支払調書提出省略分を含む。）」欄には、支払調書の提出省略限度額以下のため支払調書',
    '２ 「左のうち、支払調書を提出するものの合計」欄には、この合計表とともに支払調書を提出するもの',
    'について、その合計を記載する。',
]), '国外公社債等の利子等の支払調書合計表 記載要領')

# 見出しの次が本文の箇条なら続けない
check('【】の見出しの次が箇条なら見出しだけ', m.guess_title([
    '【教育資金管理契約の終了に関する調書合計表】',
    '１ 「所轄税務署名」欄には、提出義務者の所轄税務署名を記載する。',
]), '教育資金管理契約の終了に関する調書合計表')

# 発遣文書（今までどおり「〜について（法令解釈通達）」の行）
check('発遣文書: 「〜について（法令解釈通達）」の行を題名にする（今までどおり）', m.guess_title([
    '課個2-11',
    '令和8年9月10日',
    '国税局長 殿',
    '国税庁長官',
    '法定資料の合計表の様式の制定について（法令解釈通達）の一部改正について（法令解釈通達）',
    '標記のことについて、下記のとおり定めたから、これにより取り扱われたい。',
]), '法定資料の合計表の様式の制定について（法令解釈通達）の一部改正について（法令解釈通達）')

# 「について」を含むのが本文の文だけなら、その文は採らない（後ろの名前らしい行に落ちる）
check('「について」が「。」で終わる文にしか無ければ文を採らない', m.guess_title([
    '標記のことについて、下記のとおり定めたから、これにより取り扱われたい。',
    '譲渡所得の申告に関する取扱い一覧表',
]), '譲渡所得の申告に関する取扱い一覧表')

# 【】の次が括弧書きなら続けない（hotei/980216/pdf/kisai01.pdf）
check('【】の見出しの次が括弧書きなら見出しだけ', m.guess_title([
    '【国外送金等調書】',
    '（備 考）',
    '１ この調書は、内国税の適正な課税の確保を図るための国外送金等に係る調書の提出等に関する法律第４条',
]), '国外送金等調書')

# 箇条の頭の付いた見出しは今までどおり採る（shotoku/gensen/130628/pdf/08.pdf）
check('「１ 〜の記録要領」は今までどおり採る', m.guess_title([
    '１ 金融商品取引業者等の営業所の長が提供する事項のレコードの内容及び記録要領',
    '金融商品取引業者等の営業所の長が、租税特別措置法第37条の14第12項に規定する特定電子情報処理組織（以下',
]), '１ 金融商品取引業者等の営業所の長が提供する事項のレコードの内容及び記録要領')

check('行が無ければ None', m.guess_title([]), None)

print('\n%d 件 FAIL' % fails if fails else '\nすべて通過')
sys.exit(1 if fails else 0)
